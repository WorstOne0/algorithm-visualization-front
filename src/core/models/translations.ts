export const TRANSLATIONS = { en, pt };

export type Lang = keyof typeof TRANSLATIONS;

export type Theme = "dark" | "light";

// Copy that belongs to a data row (a family's intro, a step's note) carries both languages itself.
export type Localized<T = string> = Record<Lang, T>;

export const localize = <T>(value: Localized<T>, lang: Lang) => value[lang];

export const LOCALES: Record<Lang, string> = { en: "en-US", pt: "pt-BR" };
